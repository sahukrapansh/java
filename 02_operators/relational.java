public class relational {
    public static void main(String[] args) {
        
        // relational operator / comparasion operator

        int A = 10;
        int B = 5;

        System.out.println((A == B));
        System.out.println((A != B));
        System.out.println((A <= B));
        System.out.println((A >= B));
        System.out.println((A < B));
        System.out.println((A > B));
    }
    
}

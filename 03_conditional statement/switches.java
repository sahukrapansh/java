public class switches {
    public static void main(String[] args) {
        int number = 2;

        switch(number) {
            case 1:
                System.out.println("mango");
                break;
            case 2:
                System.out.println("banana");
                break;
            case 3:
                System.out.println("grapes");
                break;
            default:
                System.out.println("invalid");
        }
    }
}